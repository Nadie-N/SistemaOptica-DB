    private void btnbuscarcatalogoActionPerformed(java.awt.event.ActionEvent evt) {                                                   
       String busqueda = txtbuscarcatalogo.getText().trim().toLowerCase();
        DefaultTableModel modelo = (DefaultTableModel) jtablecatalogo.getModel();
        
        // Si la caja está vacía, recargamos todo
        if (busqueda.isEmpty()) {
            cargarDatos();
            return;
        }
        
        modelo.setRowCount(0); // Limpiamos tabla
        int filaEncontrada = -1;
        int contadorFilas = 0;
        
        for (Producto p : listaArosOriginal) {
            String nombre = p.getNombre() != null ? p.getNombre().toLowerCase() : "";
            String idStr = String.valueOf(p.getIdProducto());
            
            // Coincide si el ID es exacto o si el nombre contiene el texto
            if (idStr.equals(busqueda) || nombre.contains(busqueda)) {
                modelo.addRow(new Object[]{
                    p.getIdProducto(), p.getNombre(), p.getMarca(), p.getPrecio(), p.getStock()
                });
                if (filaEncontrada == -1) filaEncontrada = contadorFilas;
                contadorFilas++;
            }
        }
        
        // Resaltar y hacer scroll
        if (filaEncontrada != -1) {
            jtablecatalogo.setRowSelectionInterval(filaEncontrada, filaEncontrada);
            jtablecatalogo.scrollRectToVisible(jtablecatalogo.getCellRect(filaEncontrada, 0, true));
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "No se encontró ningún aro con ese ID o Nombre.", "Sin resultados", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            cargarDatos();
        }
    }//GEN-LAST:event_txtbuscarcatalogoActionPerformed

