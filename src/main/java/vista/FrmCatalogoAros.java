        private void cargarDatos() {
        DefaultTableModel modelo = (DefaultTableModel) jtablecatalogo.getModel();
        modelo.setRowCount(0);
        
        // Obtenemos los datos de la BD y los guardamos en la lista global
        listaArosOriginal = controller.listarPorTipo("ARO");
        
        for (Producto p : listaArosOriginal) {
            modelo.addRow(new Object[]{
                p.getIdProducto(), p.getNombre(), p.getMarca(), p.getPrecio(), p.getStock()
            });
        }
    }
