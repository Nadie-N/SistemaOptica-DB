    private void btnquitarventasActionPerformed(java.awt.event.ActionEvent evt) {                                                
                                                    
        int filaSeleccionada = jtableventas.getSelectedRow();
        if (filaSeleccionada == -1) {
            JOptionPane.showMessageDialog(this, "Selecciona un producto de la tabla para quitarlo.");
            return;
        }
        
        // Restamos el subtotal de ese producto al total acumulado
        double subtotalQuitar = (double) modeloDetalle.getValueAt(filaSeleccionada, 3);
        totalAcumulado -= subtotalQuitar;
        
        // Lo quitamos de la lista (carrito) y de la tabla
        carrito.remove(filaSeleccionada);
        modeloDetalle.removeRow(filaSeleccionada);
        
        // Actualizamos los totales en pantalla
        actualizarTotales(totalAcumulado);
    }                                               

