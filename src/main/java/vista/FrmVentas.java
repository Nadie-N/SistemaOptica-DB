    private void btnagregarventasActionPerformed(java.awt.event.ActionEvent evt) {                                                 
                                                      
        try {
            // Pedimos el ID del producto y el precio mediante ventanas de texto
            String idStr = JOptionPane.showInputDialog(this, "Ingrese el ID del producto:");
            if (idStr == null) return; // Si presiona Cancelar
            
            String precioStr = JOptionPane.showInputDialog(this, "Ingrese el precio del producto:");
            if (precioStr == null) return;
            
            int idProducto = Integer.parseInt(idStr);
            double precio = Double.parseDouble(precioStr);
            int cantidad = Integer.parseInt(txtcantidadventas.getText());
            
            if (cantidad <= 0) {
                JOptionPane.showMessageDialog(this, "La cantidad debe ser mayor a 0.");
                return;
            }
            
            double subtotal = cantidad * precio;
            
            DetalleVenta detalle = new DetalleVenta();
            detalle.setIdProducto(idProducto);
            detalle.setCantidad(cantidad);
            detalle.setPrecioUnitario(precio);
            detalle.setSubtotal(subtotal);
            
            carrito.add(detalle);
            // Asegúrate de que las columnas de la tabla coincidan con esto
            modeloDetalle.addRow(new Object[]{idProducto, cantidad, precio, subtotal});
            
            totalAcumulado += subtotal;
            actualizarTotales(totalAcumulado);
            txtcantidadventas.setText(""); // Limpiamos la cantidad
            
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Verifica que el ID, precio y cantidad sean números válidos.");
        }
    
    }

    private void actualizarTotales(double subtotal) {
        double impuesto = subtotal * 0.18;
        double total = subtotal + impuesto;
        
        jlabelsubtotalventas.setText("Subtotal: S/ " + String.format("%.2f", subtotal));
        jlabelimpuestolventas.setText("Impuesto (18%): S/ " + String.format("%.2f", impuesto));
        jlabeltotallventas.setText("Total: S/ " + String.format("%.2f", total));
    }                                                

    private void btnregistrarventasActionPerformed(java.awt.event.ActionEvent evt) {                                                   
                                                      
        if (carrito.isEmpty()) {
            JOptionPane.showMessageDialog(this, "El carrito está vacío. Agregue al menos un producto.");
            return;
        }

        try {
            Venta venta = new Venta();
            venta.setIdCliente(Integer.parseInt(txtidclienteventas.getText()));
            venta.setIdVendedor(Integer.parseInt(txtidvendedorventas.getText()));
            venta.setIdMedicion(Integer.parseInt(txtidmedicionventas.getText()));
            venta.setFechaVenta(new Date(System.currentTimeMillis()));
            venta.setSubtotal(totalAcumulado);
            venta.setImpuesto(totalAcumulado * 0.18);
            venta.setTotal(totalAcumulado * 1.18);

            // CORRECCIÓN IMPORTANTE: Tu tabla Ventas exige IdAro.
            // Tomamos el ID del primer producto del carrito para asignarlo como IdAro.
            venta.setIdAro(carrito.get(0).getIdProducto());

            boolean exito = controller.procesarVenta(venta, carrito);
            
            if (exito) {
                JOptionPane.showMessageDialog(this, "Venta registrada con éxito.");
                
                // Limpiamos el carrito y la tabla
                carrito.clear();
                modeloDetalle.setRowCount(0);
                totalAcumulado = 0.0; // Reiniciar la variable del total
                actualizarTotales(0.0);
                
                // --- LIMPIEZA DE CAMPOS ---
                txtidclienteventas.setText("");
                txtidvendedorventas.setText("");
                txtidmedicionventas.setText("");
                txtcantidadventas.setText("");
                
            } else {
                JOptionPane.showMessageDialog(this, "Error al registrar la venta en la base de datos. Verifique los IDs ingresados.");
            }
        } catch (NumberFormatException e) {
            // Error si el usuario deja un campo vacío o escribe letras en los IDs
            JOptionPane.showMessageDialog(this, "Revisa los IDs: deben ser números enteros y no pueden estar vacíos.", "Error de formato", JOptionPane.WARNING_MESSAGE);
        } catch (Exception e) {
            // Error general (por ejemplo, si falla la llave foránea en la BD)
            JOptionPane.showMessageDialog(this, "Ocurrió un error inesperado al registrar la venta.", "Error", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace(); // Imprime el error real en la consola para debug
        }
    }                                                  

